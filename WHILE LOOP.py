# while loop
# while hasilnya akan selalu true/false
# jika hasilnya true, maka program akan dijalankan
angka = 1
print (f'angka sekarang = {angka}')
while angka < 5:
    # angka awal sekarang adalah 1, dan 1 lebiih kecil dari 5, maka program akan jalan
    # sampai pada angka lebih dari 5, maka program akan berhenti
    angka +=  1 # setiap loop akan ditambah satu
    print (f'angka sekarang = {angka}')
    print('irgi achmad f')